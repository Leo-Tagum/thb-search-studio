// Inline text rules for agent-written strings. Only two constructs exist: **bold** and [text](https://url).
// Everything else is escaped, and raw angle brackets are rejected, so an agent cannot inject markup.
export type InlineLink = { text: string; url: string };
export type InlineParse = { html: string; links: InlineLink[]; plain: string; errors: string[] };

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const TOKEN = /\*\*([^*]+)\*\*|\[([^\]]+)\]\((https:\/\/[^\s)]+)\)/g;

export function parseInline(src: string): InlineParse {
  const errors: string[] = [];
  if (/[<>]/.test(src)) errors.push("raw < or > is not allowed in text (markup is generated by the renderer)");
  if (/\[[^\]]*\]\((?!https:\/\/)[^)]*\)/.test(src)) errors.push("links must be https:// URLs");
  const links: InlineLink[] = [];
  let html = ""; let plain = ""; let last = 0;
  for (const m of src.matchAll(TOKEN)) {
    const before = src.slice(last, m.index);
    html += esc(before); plain += before;
    if (m[1] !== undefined) { html += `<strong>${esc(m[1])}</strong>`; plain += m[1]; }
    else {
      links.push({ text: m[2], url: m[3] });
      const ext = !/^https:\/\/(www\.)?twinhomebuyer\.com(\/|$)/.test(m[3]);
      html += `<a href="${esc(m[3])}"${ext ? ' target="_blank" rel="noopener"' : ""}>${esc(m[2])}</a>`;
      plain += m[2];
    }
    last = (m.index ?? 0) + m[0].length;
  }
  html += esc(src.slice(last)); plain += src.slice(last);
  if (/\*\*|\[[^\]]*\]\(/.test(plain)) errors.push("unbalanced bold or link markup");
  return { html, links, plain, errors };
}
export const wordCount = (s: string) => (s.trim().match(/\S+/g) ?? []).length;
